"""Bit-for-bit comparison with snapshots from Rust commit c240697.

The fixture was generated by running the unchanged original game and sensor
modules with rand 0.10.3 and the action/pause schedule below. Each seed runs
12,000 ticks, covering serve delays, collisions, goals and round resets.
"""

import json
from pathlib import Path
import platform
import struct
import sys
import unittest

from p0p0l4.__main__ import Simulation
from p0p0l4.game import GameConfig
from p0p0l4.rng import new_rng


def bits(value, code):
    return struct.unpack("<I" if code == "f" else "<Q", struct.pack("<" + code, value))[0]


def snapshot(state):
    return {
        "f32": [bits(value, "f") for value in (
            state.player1.position.x, state.player1.position.y,
            state.player2.position.x, state.player2.position.y,
            state.ball.position.x, state.ball.position.y, state.ball.dx, state.ball.dy, state.ball.velocity)],
        "f64": [bits(state.round_time, "d"), bits(state.ball.timer, "d")],
        "stats": [state.round_count, state.p1_goals, state.p2_goals, state.p1_wins, state.p2_wins, int(state.round_winner)],
        "actions": [state.player1.dx, state.player2.dx],
    }


def buffer_hash(buffer):
    value = 0xCBF29CE484222325
    for pixel in buffer:
        value = ((value ^ bits(pixel, "f")) * 0x100000001B3) & ((1 << 64) - 1)
    return value


class RustParityTests(unittest.TestCase):
    @unittest.skipUnless(sys.platform == "darwin" and platform.machine() == "arm64",
                         "Full bitwise fixture uses macOS ARM64's native sinf/cosf")
    def test_original_game_and_sensors(self):
        references = {}
        fixture = Path(__file__).parent / "fixtures" / "rust_reference.jsonl"
        for line in fixture.read_text().splitlines():
            reference = json.loads(line)
            references.setdefault(reference["seed"], {})[reference["tick"]] = reference
        for seed, frames in references.items():
            simulation = Simulation(GameConfig(seed=seed))
            for tick in range(max(frames) + 1):
                if tick:
                    simulation.state.player1.dx = (1, -1, 0)[(tick // 43) % 3]
                    simulation.state.is_paused = 250 <= tick <= 280 or 7000 <= tick <= 7020
                    simulation.tick()
                if tick in frames:
                    with self.subTest(seed=seed, tick=tick):
                        self.assertEqual(snapshot(simulation.state), frames[tick]["state"])
                        self.assertEqual([buffer_hash(buffer) for buffer in (
                            simulation.raster_buffer_curr, simulation.sense_buffer_on, simulation.sense_buffer_off)],
                            frames[tick]["buffers"])

    def test_rng_and_float_sampling_are_portable(self):
        fixture = Path(__file__).parent / "fixtures" / "rust_rng.json"
        for reference in json.loads(fixture.read_text()):
            with self.subTest(seed=reference["seed"]):
                rng = new_rng(reference["seed"])
                self.assertEqual([rng.next_u32() for _ in reference["words"]], reference["words"])
                self.assertEqual([bits(rng.random_range(-65.0, 65.0), "f") for _ in reference["floats"]],
                                 reference["floats"])
                self.assertEqual([rng.random_bool(0.5) for _ in reference["bools"]], reference["bools"])


if __name__ == "__main__":
    unittest.main()
